-- PostgreSQL initialization script
-- Creates databases and extensions for all services

-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Create databases for services
CREATE DATABASE openwebui;
CREATE DATABASE openwebui_vector;  -- Separate database for vector storage
CREATE DATABASE mcpo;
CREATE DATABASE n8n;
CREATE DATABASE dockploy;
CREATE DATABASE graphiti;

-- Grant permissions
GRANT ALL PRIVILEGES ON DATABASE openwebui TO openwebui;
GRANT ALL PRIVILEGES ON DATABASE openwebui_vector TO openwebui;  -- Grant vector DB access
GRANT ALL PRIVILEGES ON DATABASE mcpo TO mcpo;
GRANT ALL PRIVILEGES ON DATABASE n8n TO n8n;
GRANT ALL PRIVILEGES ON DATABASE dockploy TO dockploy;
GRANT ALL PRIVILEGES ON DATABASE graphiti TO graphiti;

-- Connect to each database and enable extensions + set permissions
\c openwebui
CREATE EXTENSION IF NOT EXISTS vector;
-- Grant schema permissions (critical for Open WebUI)
GRANT ALL ON SCHEMA public TO openwebui;
GRANT ALL ON ALL TABLES IN SCHEMA public TO openwebui;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO openwebui;
GRANT ALL ON ALL FUNCTIONS IN SCHEMA public TO openwebui;
-- Set default privileges for future objects
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO openwebui;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO openwebui;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO openwebui;

\c openwebui_vector
CREATE EXTENSION IF NOT EXISTS vector;
-- Grant schema permissions for vector database
GRANT ALL ON SCHEMA public TO openwebui;
GRANT ALL ON ALL TABLES IN SCHEMA public TO openwebui;
